-- Working Knowledge loot pools.
--
-- One pool per procedural distribution. Each pool registers a single
-- placeholder item into that distribution (see WK_Distributions.lua); once the
-- container is filled, WK_LootReplace.lua swaps the placeholder for a random
-- document drawn from `docs`.
--
-- `weight` is the whole pool's spawn weight, not a per-document weight. In
-- ItemPickerJava every list entry is rolled independently once per container
-- roll, and weight is effectively a percent chance, so the expected number of
-- WK documents in a container is  rolls * weight / 100.  Adding or removing
-- documents from `docs` therefore does not change how often one spawns, only
-- which ones can.
--
-- Other mods can retune or extend this without overwriting the file:
--
--     local pools = require "WK_LootPools"
--     table.insert(pools.list.OfficeDesk.docs, "MyMod_ExpenseReport")
--     pools.list.FilingCabinetGeneric.weight = 1.25

